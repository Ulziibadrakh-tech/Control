/**
 * Every word the interface shows, in English and Mongolian.
 *
 * Writing rules (see docs/DESIGN.md): short sentences, everyday words, no
 * jargon ("suggestion", never "change request"; "What changed", never
 * "history log"). Mongolian phrases use "subject verb: “thing”" so that quoted
 * task names never need case endings.
 *
 * `mn` is typed against `en`, so a missing or extra key is a compile error.
 */

export type Params = Readonly<Record<string, string | number>>;
export type Msg = string | ((p: Params) => string);

